-- ServeGood initial schema.
-- Conventions: bigint identity keys, created_at/updated_at on every table,
-- status columns as checked varchar (mapped to Java enums), soft deletion via
-- deleted_at where a record is referenced by history (users, restaurants,
-- menu items, reviews).

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------- identity

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(40)  NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

INSERT INTO roles (name) VALUES ('CONSUMER'), ('RESTAURANT_OWNER'), ('REVIEWER'), ('ADMIN');

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(255) NOT NULL UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,
    full_name            VARCHAR(120) NOT NULL,
    phone                VARCHAR(30),
    avatar_url           VARCHAR(500),
    status               VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    email_notifications  BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at        TIMESTAMPTZ,
    deleted_at           TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE user_roles (
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id  BIGINT NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ  NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- files

CREATE TABLE stored_files (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key        VARCHAR(300) NOT NULL UNIQUE,
    url                VARCHAR(500) NOT NULL,
    original_filename  VARCHAR(255),
    content_type       VARCHAR(100) NOT NULL,
    size_bytes         BIGINT       NOT NULL,
    purpose            VARCHAR(30)  NOT NULL CHECK (purpose IN ('RESTAURANT', 'MENU_ITEM', 'REVIEW', 'HYGIENE_EVIDENCE', 'AVATAR', 'ADVERTISEMENT')),
    uploaded_by        BIGINT       REFERENCES users (id),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- restaurants

CREATE TABLE restaurant_categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80)  NOT NULL,
    slug         VARCHAR(80)  NOT NULL UNIQUE,
    kind         VARCHAR(20)  NOT NULL CHECK (kind IN ('CUISINE', 'DINING_STYLE')),
    description  VARCHAR(300),
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE restaurants (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(150)  NOT NULL,
    slug                    VARCHAR(170)  NOT NULL UNIQUE,
    description             TEXT,
    phone                   VARCHAR(30),
    email                   VARCHAR(255),
    website                 VARCHAR(300),
    price_level             INTEGER       NOT NULL DEFAULT 2 CHECK (price_level BETWEEN 1 AND 4),
    cost_for_two            INTEGER       CHECK (cost_for_two >= 0),
    cover_image_url         VARCHAR(500),
    comparison_basket       VARCHAR(300),
    status                  VARCHAR(20)   NOT NULL DEFAULT 'PENDING_APPROVAL'
                                CHECK (status IN ('PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'SUSPENDED')),
    status_reason           VARCHAR(500),
    -- Rating aggregates. Recomputed from VERIFIED reviews only; advertising never writes these.
    avg_overall             NUMERIC(3, 2),
    avg_food                NUMERIC(3, 2),
    avg_service             NUMERIC(3, 2),
    avg_hygiene             NUMERIC(3, 2),
    review_count            INTEGER       NOT NULL DEFAULT 0,
    -- Hygiene, from the latest APPROVED audit. Kept separate from food ratings.
    hygiene_score           INTEGER       CHECK (hygiene_score BETWEEN 0 AND 100),
    hygiene_audit_id        BIGINT,
    hygiene_verified_until  DATE,
    view_count              BIGINT        NOT NULL DEFAULT 0,
    deleted_at              TIMESTAMPTZ,
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_restaurants_status ON restaurants (status) WHERE deleted_at IS NULL;
CREATE INDEX idx_restaurants_name_trgm ON restaurants USING gin (name gin_trgm_ops);
CREATE INDEX idx_restaurants_avg_overall ON restaurants (avg_overall);
CREATE INDEX idx_restaurants_hygiene ON restaurants (hygiene_score);

CREATE TABLE restaurant_addresses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT        NOT NULL UNIQUE REFERENCES restaurants (id) ON DELETE CASCADE,
    line1          VARCHAR(200)  NOT NULL,
    line2          VARCHAR(200),
    locality       VARCHAR(100)  NOT NULL,
    city           VARCHAR(100)  NOT NULL,
    state          VARCHAR(100)  NOT NULL,
    postal_code    VARCHAR(12),
    country        VARCHAR(60)   NOT NULL DEFAULT 'India',
    latitude       NUMERIC(9, 6),
    longitude      NUMERIC(9, 6),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_restaurant_addresses_locality ON restaurant_addresses (lower(locality));
CREATE INDEX idx_restaurant_addresses_city ON restaurant_addresses (lower(city));
CREATE INDEX idx_restaurant_addresses_geo ON restaurant_addresses (latitude, longitude);

CREATE TABLE restaurant_owners (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT       NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    owner_role     VARCHAR(20)  NOT NULL DEFAULT 'OWNER' CHECK (owner_role IN ('OWNER', 'MANAGER')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (restaurant_id, user_id)
);
CREATE INDEX idx_restaurant_owners_user ON restaurant_owners (user_id);

CREATE TABLE restaurant_category_assignments (
    restaurant_id  BIGINT NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    category_id    BIGINT NOT NULL REFERENCES restaurant_categories (id) ON DELETE CASCADE,
    PRIMARY KEY (restaurant_id, category_id)
);
CREATE INDEX idx_rca_category ON restaurant_category_assignments (category_id);

CREATE TABLE restaurant_opening_hours (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT       NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    day_of_week    INTEGER      NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    opens_at       TIME         NOT NULL,
    closes_at      TIME         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_opening_hours_restaurant ON restaurant_opening_hours (restaurant_id, day_of_week);

CREATE TABLE restaurant_images (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT        NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    url            VARCHAR(500)  NOT NULL,
    alt_text       VARCHAR(250),
    sort_order     INTEGER       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_restaurant_images_restaurant ON restaurant_images (restaurant_id);

CREATE TABLE restaurant_views (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT       NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    user_id        BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_restaurant_views_restaurant ON restaurant_views (restaurant_id, created_at);
CREATE INDEX idx_restaurant_views_user ON restaurant_views (user_id, created_at DESC);

-- ---------------------------------------------------------------- menus

CREATE TABLE menus (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT        NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    name           VARCHAR(100)  NOT NULL,
    description    VARCHAR(300),
    sort_order     INTEGER       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_menus_restaurant ON menus (restaurant_id);

CREATE TABLE menu_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id        BIGINT         NOT NULL REFERENCES menus (id) ON DELETE CASCADE,
    restaurant_id  BIGINT         NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    name           VARCHAR(150)   NOT NULL,
    description    VARCHAR(500),
    price          NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    image_url      VARCHAR(500),
    available      BOOLEAN        NOT NULL DEFAULT TRUE,
    vegetarian     BOOLEAN        NOT NULL DEFAULT FALSE,
    sort_order     INTEGER        NOT NULL DEFAULT 0,
    deleted_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX idx_menu_items_menu ON menu_items (menu_id);
CREATE INDEX idx_menu_items_restaurant ON menu_items (restaurant_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_menu_items_name_trgm ON menu_items USING gin (name gin_trgm_ops);

-- ---------------------------------------------------------------- reviews

CREATE TABLE reviews (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id    BIGINT        NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    user_id          BIGINT        NOT NULL REFERENCES users (id),
    overall_rating   INTEGER       NOT NULL CHECK (overall_rating BETWEEN 1 AND 5),
    food_rating      INTEGER       NOT NULL CHECK (food_rating BETWEEN 1 AND 5),
    service_rating   INTEGER       NOT NULL CHECK (service_rating BETWEEN 1 AND 5),
    hygiene_rating   INTEGER       NOT NULL CHECK (hygiene_rating BETWEEN 1 AND 5),
    title            VARCHAR(150),
    comment          TEXT          NOT NULL,
    visit_date       DATE,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED', 'FLAGGED')),
    reviewer_review  BOOLEAN       NOT NULL DEFAULT FALSE,
    moderation_note  VARCHAR(500),
    moderated_by     BIGINT        REFERENCES users (id),
    moderated_at     TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);
-- One live review per person per restaurant.
CREATE UNIQUE INDEX uq_reviews_user_restaurant ON reviews (user_id, restaurant_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_reviews_restaurant_status ON reviews (restaurant_id, status) WHERE deleted_at IS NULL;
CREATE INDEX idx_reviews_status ON reviews (status) WHERE deleted_at IS NULL;

CREATE TABLE review_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   BIGINT        NOT NULL REFERENCES reviews (id) ON DELETE CASCADE,
    url         VARCHAR(500)  NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_review_images_review ON review_images (review_id);

CREATE TABLE review_responses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id     BIGINT       NOT NULL UNIQUE REFERENCES reviews (id) ON DELETE CASCADE,
    responder_id  BIGINT       NOT NULL REFERENCES users (id),
    body          TEXT         NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Optional per-dish ratings attached to a review.
CREATE TABLE food_ratings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id     BIGINT        NOT NULL REFERENCES reviews (id) ON DELETE CASCADE,
    menu_item_id  BIGINT        REFERENCES menu_items (id) ON DELETE SET NULL,
    dish_name     VARCHAR(150)  NOT NULL,
    rating        INTEGER       NOT NULL CHECK (rating BETWEEN 1 AND 5),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_food_ratings_review ON food_ratings (review_id);

CREATE TABLE review_reports (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id      BIGINT        NOT NULL REFERENCES users (id),
    report_type      VARCHAR(40)   NOT NULL CHECK (report_type IN ('FAKE_REVIEW', 'INCORRECT_RESTAURANT_INFO', 'INAPPROPRIATE_CONTENT', 'INCORRECT_HYGIENE_INFO')),
    restaurant_id    BIGINT        NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    review_id        BIGINT        REFERENCES reviews (id) ON DELETE CASCADE,
    details          TEXT          NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    resolution_note  VARCHAR(500),
    resolved_by      BIGINT        REFERENCES users (id),
    resolved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_review_reports_status ON review_reports (status, created_at);

-- ---------------------------------------------------------------- hygiene

CREATE TABLE reviewer_assignments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reviewer_id    BIGINT       NOT NULL REFERENCES users (id),
    restaurant_id  BIGINT       NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    assigned_by    BIGINT       REFERENCES users (id),
    due_date       DATE,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ASSIGNED' CHECK (status IN ('ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    notes          VARCHAR(500),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_assignments_reviewer ON reviewer_assignments (reviewer_id, status);

CREATE TABLE hygiene_audits (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id    BIGINT       NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    reviewer_id      BIGINT       NOT NULL REFERENCES users (id),
    assignment_id    BIGINT       REFERENCES reviewer_assignments (id) ON DELETE SET NULL,
    audit_date       DATE         NOT NULL,
    overall_score    INTEGER      CHECK (overall_score BETWEEN 0 AND 100),
    status           VARCHAR(20)  NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'EXPIRED')),
    findings         TEXT,
    recommendations  TEXT,
    decision_note    VARCHAR(500),
    decided_by       BIGINT       REFERENCES users (id),
    decided_at       TIMESTAMPTZ,
    submitted_at     TIMESTAMPTZ,
    valid_until      DATE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_hygiene_audits_restaurant ON hygiene_audits (restaurant_id, status);
CREATE INDEX idx_hygiene_audits_reviewer ON hygiene_audits (reviewer_id);
CREATE INDEX idx_hygiene_audits_status ON hygiene_audits (status);

ALTER TABLE restaurants
    ADD CONSTRAINT fk_restaurants_hygiene_audit FOREIGN KEY (hygiene_audit_id) REFERENCES hygiene_audits (id) ON DELETE SET NULL;

CREATE TABLE hygiene_audit_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id    BIGINT       NOT NULL REFERENCES hygiene_audits (id) ON DELETE CASCADE,
    category    VARCHAR(40)  NOT NULL CHECK (category IN ('KITCHEN_CLEANLINESS', 'FOOD_STORAGE', 'FOOD_HANDLING', 'STAFF_HYGIENE',
                                                          'PEST_CONTROL', 'WASTE_MANAGEMENT', 'EQUIPMENT_CLEANLINESS', 'PREMISES_CLEANLINESS')),
    score       INTEGER      NOT NULL CHECK (score BETWEEN 0 AND 10),
    weight      INTEGER      NOT NULL CHECK (weight > 0),
    notes       TEXT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (audit_id, category)
);

CREATE TABLE hygiene_evidence (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id    BIGINT        NOT NULL REFERENCES hygiene_audits (id) ON DELETE CASCADE,
    url         VARCHAR(500)  NOT NULL,
    caption     VARCHAR(250),
    category    VARCHAR(40),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_hygiene_evidence_audit ON hygiene_evidence (audit_id);

-- ---------------------------------------------------------------- delivery

CREATE TABLE delivery_providers (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(80)   NOT NULL,
    slug              VARCHAR(80)   NOT NULL UNIQUE,
    website_url       VARCHAR(300),
    logo_url          VARCHAR(500),
    integration_type  VARCHAR(20)   NOT NULL DEFAULT 'MANUAL' CHECK (integration_type IN ('MANUAL', 'API')),
    direct_channel    BOOLEAN       NOT NULL DEFAULT FALSE,
    active            BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order        INTEGER       NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE restaurant_delivery_options (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id  BIGINT        NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    provider_id    BIGINT        NOT NULL REFERENCES delivery_providers (id),
    ordering_url   VARCHAR(500),
    available      BOOLEAN       NOT NULL DEFAULT TRUE,
    notes          VARCHAR(300),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (restaurant_id, provider_id)
);

-- Price history. The newest row per option is the current price.
CREATE TABLE delivery_prices (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id           BIGINT          NOT NULL REFERENCES restaurant_delivery_options (id) ON DELETE CASCADE,
    basket_description  VARCHAR(300)    NOT NULL,
    food_subtotal       NUMERIC(10, 2)  NOT NULL CHECK (food_subtotal >= 0),
    delivery_fee        NUMERIC(10, 2)  NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    platform_fee        NUMERIC(10, 2)  NOT NULL DEFAULT 0 CHECK (platform_fee >= 0),
    other_fees          NUMERIC(10, 2)  NOT NULL DEFAULT 0 CHECK (other_fees >= 0),
    discount            NUMERIC(10, 2)  NOT NULL DEFAULT 0 CHECK (discount >= 0),
    final_total         NUMERIC(10, 2)  NOT NULL,
    source              VARCHAR(30)     NOT NULL CHECK (source IN ('ADMIN_MANUAL', 'RESTAURANT_SUBMITTED', 'PROVIDER_API')),
    recorded_by         BIGINT          REFERENCES users (id),
    recorded_at         TIMESTAMPTZ     NOT NULL DEFAULT now(),
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ     NOT NULL DEFAULT now()
);
CREATE INDEX idx_delivery_prices_option ON delivery_prices (option_id, recorded_at DESC);

-- ---------------------------------------------------------------- advertising

CREATE TABLE advertisement_campaigns (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id     BIGINT          NOT NULL REFERENCES restaurants (id) ON DELETE CASCADE,
    created_by        BIGINT          REFERENCES users (id),
    name              VARCHAR(120)    NOT NULL,
    target_location   VARCHAR(120),
    start_date        DATE            NOT NULL,
    end_date          DATE            NOT NULL,
    budget            NUMERIC(12, 2)  NOT NULL CHECK (budget >= 0),
    status            VARCHAR(20)     NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING', 'ACTIVE', 'PAUSED', 'EXPIRED', 'REJECTED')),
    payment_status    VARCHAR(20)     NOT NULL DEFAULT 'UNPAID' CHECK (payment_status IN ('UNPAID', 'PAID', 'REFUNDED')),
    status_reason     VARCHAR(500),
    reviewed_by       BIGINT          REFERENCES users (id),
    reviewed_at       TIMESTAMPTZ,
    created_at        TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ     NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);
CREATE INDEX idx_campaigns_restaurant ON advertisement_campaigns (restaurant_id);
CREATE INDEX idx_campaigns_status_dates ON advertisement_campaigns (status, start_date, end_date);

CREATE TABLE advertisements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT        NOT NULL REFERENCES advertisement_campaigns (id) ON DELETE CASCADE,
    placement    VARCHAR(30)   NOT NULL CHECK (placement IN ('HOMEPAGE', 'SEARCH_RESULTS', 'CATEGORY_PAGE', 'LOCAL_RECOMMENDATIONS')),
    headline     VARCHAR(120),
    image_url    VARCHAR(500),
    category_id  BIGINT        REFERENCES restaurant_categories (id) ON DELETE SET NULL,
    impressions  BIGINT        NOT NULL DEFAULT 0,
    clicks       BIGINT        NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, placement)
);
CREATE INDEX idx_advertisements_placement ON advertisements (placement);

-- ---------------------------------------------------------------- engagement

CREATE TABLE favorites (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
